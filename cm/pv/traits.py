"""Trait definitions for persona-vector extraction: the 7 upstream traits plus the 30 from D-020.

Upstream files: vendor/persona_vectors/trait_data_{extract,eval}/ (safety-research/persona_vectors @ b8e0f04).
Ours: data/traits/{extract,eval}/ (generated by cm.gen_traits, reviewed and approved by Harsh 2026-10-20).

Sides and system prompts follow upstream eval_persona.py / scripts/generate_vec.sh:
  "You are {a/an} {name} assistant. {instruction}"
Plain traits: side pos (name = trait) and neg (name = "helpful"), as upstream.
Context-sensitive traits (D-024): sides virtue (name = trait), excess and deficiency (name = the vice), and a
neutral side "You are a helpful assistant." with no instruction, so the three can be placed against one baseline.
Gemma has no system role; its chat template prepends the system text to the first user turn.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

from ..paths import REPO

UPSTREAM = ["evil", "sycophantic", "hallucinating", "optimistic", "impolite", "apathetic", "humorous"]
VENDOR = REPO / "vendor" / "persona_vectors"
OURS = REPO / "data" / "traits"


def slug(name: str) -> str:
    return re.sub(r"[ -]+", "_", name.strip().lower())


def persona_name(name: str) -> str:
    return re.sub(r"\s+", "-", name.strip())


def a_or_an(word: str) -> str:  # upstream eval_persona.a_or_an
    return "an" if word[0].lower() in "aeiou" else "a"


@dataclass
class Trait:
    slug: str
    name: str
    kind: str                       # "plain" or "conditional"
    source: str                     # "upstream" or "d020"
    instruction: list[dict]
    questions: list                 # str (plain) or dict with question/condition/pair (conditional)
    eval_prompts: dict              # metric -> template with {question}, {answer} (and {condition_status})
    vice_names: dict = field(default_factory=dict)  # conditional: side -> vice name

    @property
    def sides(self) -> list[str]:
        return ["pos", "neg"] if self.kind == "plain" else ["virtue", "excess", "deficiency", "neutral"]

    def system_prompt(self, side: str, k: int) -> str:
        if self.kind == "plain":
            name = persona_name(self.name) if side == "pos" else "helpful"
            return f"You are {a_or_an(name)} {name} assistant. {self.instruction[k][side]}"
        if side == "neutral":
            return "You are a helpful assistant."
        name = persona_name(self.name) if side == "virtue" else self.vice_names[side]
        return f"You are {a_or_an(name)} {name} assistant. {self.instruction[k][side]}"

    def n_instructions(self, side: str) -> int:
        return 1 if side == "neutral" else len(self.instruction)


def _vice(text: str) -> str:
    return persona_name(text.split(":")[0])


def load(slug_or_name: str, split: str = "extract") -> Trait:
    s = slug(slug_or_name)
    if s in UPSTREAM:
        d = json.loads((VENDOR / f"trait_data_{split}" / f"{s}.json").read_text())
        return Trait(s, s, "plain", "upstream", d["instruction"], d["questions"], {s: d["eval_prompt"]})
    d = json.loads((OURS / split / f"{s}.json").read_text())
    if d["kind"] == "unconditional":
        return Trait(s, d["trait"], "plain", "d020", d["instruction"], d["questions"], {s: d["eval_prompt"]})
    spec = next(x for x in json.loads((OURS / "specs.json").read_text())["conditional"] if slug(x["name"]) == s)
    return Trait(s, d["trait"], "conditional", "d020", d["instruction"], d["questions"],
                 {"virtue": d["eval_prompt_virtue"], "excess": d["eval_prompt_excess"],
                  "deficiency": d["eval_prompt_deficiency"]},
                 {"excess": _vice(spec["excess"]), "deficiency": _vice(spec["deficiency"])})


def all_slugs() -> list[str]:
    ours = json.loads((OURS / "specs.json").read_text())
    return UPSTREAM + [slug(x["name"]) for x in ours["unconditional"]] + [slug(x["name"]) for x in ours["conditional"]]


TURN = re.compile(r"^(Me|You):\s?", re.M)


def to_turns(question: str) -> list[dict]:
    """A question written as a 'Me: ... / You: ...' transcript becomes real chat turns (D-025); anything else is one
    user turn. The transcript must start with Me and end with Me, alternating."""
    parts = TURN.split(question)
    if len(parts) < 5 or parts[0].strip():
        return [{"role": "user", "content": question}]
    turns = [{"role": "user" if who == "Me" else "assistant", "content": text.strip()}
             for who, text in zip(parts[1::2], parts[2::2])]
    roles = [t["role"] for t in turns]
    if roles[0] != "user" or roles[-1] != "user" or any(a == b for a, b in zip(roles, roles[1:])):
        return [{"role": "user", "content": question}]
    return turns
