"""Helpers for the C12-C21 builders (docs/STIMULI.md). Local to this group, not shared code.

Each concept script builds its scenarios, asks gemma-4-31B-it for the cells its sources lack, and assembles
items.jsonl, heldout.jsonl and behavior.jsonl. Generation is staged:
  1. python -m cm.stimuli.build.c12           writes pending requests to outputs/stimuli/_gen/C12/requests.jsonl
  2. python -m cm.stimuli.build._disp2 combine disp2_r1 C12 C13 ...   one batch for all pending requests
  3. sbatch --array=0-2 scripts/cm_gen.sbatch disp2_r1 3; then python -m cm.stimuli.generate disp2_r1 --merge
  4. python -m cm.stimuli.build.c12           reads every responses*.jsonl under _gen/, assembles, validates
Request ids carry a hash of the prompt, so a changed prompt is regenerated and an unchanged one is reused.
A request whose output fails its check is retried with a new attempt number, up to MAX_ATTEMPTS.
"""
