def src(key: str, dataset: str, sid, license: str | None = None, url: str | None = None) -> dict:
    return {"dataset": dataset, "id": str(sid), "license": license or LIC[key], "url": url or URL.get(key, "")}


def rng(*parts) -> random.Random:
    return random.Random(int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:12], 16))


def hf_file(repo: str, rel: str) -> Path:
    """A file inside a cached HF dataset snapshot (downloaded on ada beforehand)."""
    snaps = sorted((HF_ROOT / f"datasets--{repo.replace('/', '--')}" / "snapshots").glob("*"))
    for s in reversed(snaps):
        if (s / rel).exists():
            return s / rel
    raise FileNotFoundError(f"{repo}/{rel} not in {HF_ROOT}; download it on ada first")


def load_json_any(path: Path) -> list[dict]:
    t = path.read_text().strip()
    return json.loads(t) if t.startswith("[") else [json.loads(l) for l in t.splitlines() if l.strip()]


# ---------------------------------------------------------------- A/B questions (model-written evals, CAA)

def split_ab(question: str):
    """Return (stem, {"A": text, "B": text}) for an A/B question, or None."""
    q = re.sub(r"\n\nAnswer:\s*$", "", question.strip())
    q = re.sub(r"^Question:\s*", "", q)
    m = re.search(r"\n\s*(?:Choices:\s*\n)?\s*\(A\)", q)
    if not m:
        return None
    stem, rest = q[:m.start()].strip(), q[m.start():]
    ch = dict((k, v.strip()) for k, v in re.findall(r"\(([AB])\)\s*(.+?)(?=\n\s*\([AB]\)|\Z)", rest, re.S))
    if set(ch) != {"A", "B"} or not stem:
        return None
    return stem, ch


def letter(ans: str) -> str:
    return ans.strip().strip("()").strip()


# ---------------------------------------------------------------- items

def mk(cid: str, scn: str, frame: str, pol: str, messages: list[dict], construction: str, source: dict,
       meta: dict | None = None, suffix: str | None = None, split: str | None = None) -> dict:
    readout = "response" if messages[-1]["role"] == "assistant" else "boundary"
    iid = "-".join([scn, frame, pol] + ([suffix] if suffix else []))
    return {"concept": cid, "item_id": iid, "scenario_id": scn, "frame": frame, "polarity": pol,
            "split": split or split_for(scn), "messages": messages, "readout": readout,
            "construction": construction, "source": source, "meta": meta or {}}


def mkb(cid: str, bid: str, messages: list[dict], instrument: str, scoring: dict, construction: str, source: dict,
        meta: dict | None = None) -> dict:
    """Behavior item: no polarity; the model replies at the end, scored by `scoring`."""
    return {"concept": cid, "item_id": bid, "scenario_id": bid, "split": "test", "messages": messages,
            "readout": "boundary", "construction": construction, "source": source, "instrument": instrument,
            "scoring": scoring, "meta": meta or {}}


def user(t: str) -> list[dict]:
    return [{"role": "user", "content": t}]


def ua(u: str, a: str) -> list[dict]:
    return [{"role": "user", "content": u}, {"role": "assistant", "content": a}]


def d_items(cid, scn, pos: str, neg: str, construction, source, meta, suffix=None) -> list[dict]:
    return [mk(cid, scn, "d", "pos", user(D_PROMPT.format(s=pos)), construction, source, meta, suffix),
            mk(cid, scn, "d", "neg", user(D_PROMPT.format(s=neg)), construction, source, meta, suffix)]


def ratio_ok(a: str, b: str, lo: float = 0.6, hi: float = 1.67) -> bool:
    return bool(a) and bool(b) and lo <= len(a) / len(b) <= hi


def clean(s) -> str:
    return re.sub(r"\s+", " ", str(s)).strip().strip('"').strip() if s is not None else ""


# ---------------------------------------------------------------- generation

def json_blocks(text: str) -> list:
    """Every top-level {...} block in text that parses, in order. gemma sometimes writes a block, says it made an
    error, and writes a corrected one; generate.parse_json (first brace to last brace) cannot read that."""
    out, depth, start, instr, esc = [], 0, None, False, False
    for i, ch in enumerate(text):
        if instr:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                instr = False
            continue
        if ch == '"':
            instr, esc = True, False
        elif ch == "{":
            if depth == 0:
                start = i
            depth += 1
        elif ch == "}" and depth:
            depth -= 1
            if depth == 0:
                try:
                    out.append(json.loads(text[start:i + 1]))
                except json.JSONDecodeError:
                    pass
    return out


VERIFY = """You are checking items for a research dataset. {definition}

Text 1:
<<<{t1}>>>

Text 2:
<<<{t2}>>>

Which text {question}? Answer with only the number 1 or 2."""


class Gen:
    """Collects requests for one concept and serves back checked responses."""

    def __init__(self, cid: str):
        self.cid = cid
        self.reqs: list[dict] = []
        self.resp: dict[str, dict] = {}
        for p in GEN.glob("*/responses*.jsonl"):
            for r in read_jsonl(p):
                if r["request_id"].startswith(cid + "|"):
                    self.resp[r["request_id"]] = r
        self.failed = collections.Counter()
        self.vfail = collections.Counter()

    @staticmethod
    def rid(cid, key, prompt, attempt):
        return f"{cid}|{key}|{hashlib.sha1(prompt.encode()).hexdigest()[:8]}|a{attempt}"

    def get(self, key: str, prompt: str, check, max_tokens: int = 900, temperature: float = 0.7):
        """Return the first attempt whose JSON passes `check` (a function returning the cleaned dict or None).
        Missing attempts are queued as requests; failed ones queue the next attempt."""
        for attempt in range(1, MAX_ATTEMPTS + 1):
            rid = self.rid(self.cid, key, prompt, attempt)
            r = self.resp.get(rid)
            if r is None:
                self.reqs.append({"request_id": rid, "messages": user(prompt), "max_tokens": max_tokens,
                                  "temperature": temperature if attempt == 1 else 0.9, "expect_json": True})
                return None
            if r.get("finish_reason") != "length":
                for j in [r.get("json")] + json_blocks(r.get("text", ""))[::-1]:
                    out = check(j)
                    if out is not None:
                        out["_gen_id"] = rid
                        return out
            self.failed[re.sub(r"\d+", "#", key)] += 1
        return None

    def verify(self, key: str, definition: str, question: str, pos: str, neg: str, expect: str = "pos"):
        """Greedy gemma check that a generated pair carries the contrast: shown both texts in a random order, it must
        pick the `expect` text for `question`. Returns True, False, or None while the request is pending."""
        first_pos = rng("verify", self.cid, key).random() < 0.5
        t1, t2 = (pos, neg) if first_pos else (neg, pos)
        prompt = VERIFY.format(definition=definition, t1=t1, t2=t2, question=question)
        rid = self.rid(self.cid, "verify|" + key, prompt, 1)
        r = self.resp.get(rid)
        if r is None:
            self.reqs.append({"request_id": rid, "messages": user(prompt), "max_tokens": 8, "temperature": 0.0,
                              "expect_json": False})
            return None
        m = re.search(r"[12]", r.get("text", ""))
        ok = bool(m) and (((m.group() == "1") == first_pos) == (expect == "pos"))
        if not ok:
            self.vfail[re.sub(r"\d+", "#", key)] += 1
        return ok

    def ask(self, key: str, prompt: str, max_tokens: int = 8):
        """Greedy short answer (text) or None while pending."""
        rid = self.rid(self.cid, "ask|" + key, prompt, 1)
        r = self.resp.get(rid)
        if r is None:
            self.reqs.append({"request_id": rid, "messages": user(prompt), "max_tokens": max_tokens,
                              "temperature": 0.0, "expect_json": False})
            return None
        return r.get("text", "")


def verified(results) -> bool | None:
    """None if any check is pending, else whether all passed."""
    results = list(results)
    return None if any(r is None for r in results) else all(results)


def checked(o, checks):
    """o when it exists and every verification check passes; otherwise None. `checks` maps o to a list of results."""
    return o if o and verified(checks(o)) else None

    def flush(self) -> int:
        d = GEN / self.cid
        d.mkdir(parents=True, exist_ok=True)
        write_jsonl(d / "requests.jsonl", self.reqs)
        return len(self.reqs)


def need(keys):
    """A check that requires these string keys to be non-empty; returns cleaned dict."""
    def f(j):
        if not isinstance(j, dict):
            return None
        out = {k: clean(j.get(k)) for k in keys}
        return out if all(out.values()) else None
    return f


def combine(batch: str, cids: list[str]):
    rows, seen = [], set()
    for c in cids:
        for r in read_jsonl(GEN / c / "requests.jsonl"):
            if r["request_id"] not in seen:
                seen.add(r["request_id"])
                rows.append(r)
    write_jsonl(GEN / batch / "requests.jsonl", rows)
    print(f"[combine] {batch}: {len(rows)} requests from {', '.join(cids)}")


# ---------------------------------------------------------------- outputs

def review_sample(items: list[dict], frames: list[str], n: int = 3, seed: str = "") -> list[dict]:
    """n scenarios with every applicable frame x polarity cell, spread over sub-contrasts; all their items for
    one sub-contrast each, so every cell holds exactly n items and pos/neg come from the same scenario."""
    by = collections.defaultdict(list)
    for it in items:
        by[(it["scenario_id"], it["meta"].get("contrast", ""))].append(it)
    full = [k for k, v in by.items() if {(f, p) for f in frames for p in ("pos", "neg")} <= {(i["frame"], i["polarity"]) for i in v}]
    r = rng("review", seed)
    r.shuffle(full)
    picked, used_c, used_s = [], collections.Counter(), set()
    while len(picked) < n and full:
        full.sort(key=lambda k: (used_c[k[1]], r.random()))
        k = full.pop(0)
        if k[0] in used_s:
            continue
        picked.append(k)
        used_c[k[1]] += 1
        used_s.add(k[0])
    out = []
    for k in picked:
        for f in frames:
            for p in ("pos", "neg"):
                out.append(next(i for i in by[k] if i["frame"] == f and i["polarity"] == p))
    return out


def write_all(cid: str, items: list[dict], held: list[dict], beh: list[dict], frames: list[str], report: dict):
    d = item_dir(cid)
    write_jsonl(d / "items.jsonl", items)
    write_jsonl(d / "heldout.jsonl", held)
    write_jsonl(d / "behavior.jsonl", beh)
    rs = review_sample(items, frames, 3, cid)
    rs += [dict(h, review_kind="heldout") for h in rng("rh", cid).sample(held, min(2, len(held)))]
    rs += [dict(b, review_kind="behavior") for b in rng("rb", cid).sample(beh, min(2, len(beh)))]
    write_jsonl(d / "review_sample.jsonl", rs)
    report["length_ratio_by_contrast"] = length_ratios(items)
    (d / "build_report.json").write_text(json.dumps(report, indent=1) + "\n")
    from ..validate import validate
    rep = validate(cid)
    print(f"[{cid}] scenarios {rep.get('n_scenarios')} items {rep.get('n_items')} heldout {rep.get('n_heldout')} "
          f"behavior {rep.get('n_behavior')} | errors {rep['errors']} | warnings {rep['warnings']}", flush=True)
    return rep


def length_ratios(items: list[dict]) -> dict:
    L = {(i["scenario_id"], i["frame"], i["polarity"], i["meta"].get("contrast", "")): sum(len(m["content"]) for m in i["messages"] if m["role"] != "system") for i in items}
    rat = collections.defaultdict(list)
    for (s, f, p, c), n in L.items():
        if p == "pos" and (s, f, "neg", c) in L:
            rat[f"{c or 'all'}/{f}"].append(n / L[(s, f, "neg", c)])
    return {k: round(statistics.median(v), 3) for k, v in sorted(rat.items())}


def finish(cid: str, gen: Gen) -> bool:
    """Write pending requests. Returns True when nothing is pending."""
    n = gen.flush()
    if n:
        print(f"[{cid}] {n} generation requests pending in {GEN / cid / 'requests.jsonl'}; "
              f"failed attempts so far {dict(gen.failed)}", flush=True)
    return n == 0


