def last_json(text: str):
    """The last top-level JSON object in a text. gemma sometimes writes a block, then corrects itself with a second
    one, which generate.parse_json (first brace to last brace) cannot read."""
    blocks, depth, start, in_str, esc = [], 0, None, False, False
    for i, ch in enumerate(text):
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
            continue
        if ch == '"':
            in_str = True
        elif ch == "{":
            start = i if depth == 0 else start
            depth += 1
        elif ch == "}" and depth:
            depth -= 1
            if depth == 0:
                blocks.append(text[start:i + 1])
    for b in reversed(blocks):
        try:
            return json.loads(b)
        except json.JSONDecodeError:
            continue
    return None


def responses() -> dict:
    out = {}
    for p in sorted(GEN_ROOT.glob("moral-*/responses.jsonl")):
        for r in read_jsonl(p):
            out[r["request_id"]] = r
    return out


class Gen:
    """Collects gemma-4-31B-it requests for one concept and returns answers already generated."""

    def __init__(self, cid: str):
        self.cid, self.pending, self._resp = cid, [], responses()

    def ask(self, key: str, prompt: str, max_tokens: int = 1024, temperature: float = 0.4, expect_json=True):
        rid = f"{self.cid}:{key}:{h(prompt, 10)}"
        r = self._resp.get(rid)
        if r is None:
            self.pending.append({"request_id": rid, "messages": [user(prompt)], "max_tokens": max_tokens,
                                 "temperature": temperature, "expect_json": expect_json})
            return None, rid
        if expect_json:
            if r.get("finish_reason") != "stop":
                return False, rid
            j = r.get("json") if r.get("parse_ok") else last_json(r.get("text", ""))
            return (j if j is not None else False), rid
        return (r["text"] if r.get("finish_reason") == "stop" else False), rid

    def check(self, key: str, prompt: str, test, max_tokens: int = 300):
        """A verification request at temperature 0. Returns None while pending, else test(json) as a bool."""
        j, _ = self.ask(f"verify-{key}", prompt, max_tokens=max_tokens, temperature=0.0)
        if j is None:
            return None
        try:
            return bool(isinstance(j, dict) and test(j))
        except (KeyError, TypeError, ValueError):
            return False

    def flush(self):
        p = item_dir(self.cid) / "pending_requests.jsonl"
        write_jsonl(p, self.pending)
        if self.pending:
            print(f"[{self.cid}] {len(self.pending)} generation requests pending -> {p}", flush=True)
        return len(self.pending)


