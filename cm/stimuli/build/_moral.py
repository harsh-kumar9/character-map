def as_list(x):
    if isinstance(x, (list, tuple)):
        return list(x)
    if hasattr(x, "tolist"):
        return list(x.tolist())
    try:
        return list(ast.literal_eval(str(x)))
    except (ValueError, SyntaxError):
        return [str(x)]


# ------------------------------------------------------------------------------------------------ text helpers

def h(s: str, n: int = 8) -> str:
    return hashlib.sha256(s.encode()).hexdigest()[:n]


def order(key: str) -> str:
    """Sort key for choosing candidates. It must not be h(scenario_id): schema.split_for hashes the same string, so
    taking the first n by h(scenario_id) takes only train scenarios."""
    return h("order:" + key)


def pick(pool: list, key: str):
    """Stable choice from a pool, keyed by scenario id, so pos and neg of a scenario get the same wording."""
    return pool[int(h(key), 16) % len(pool)]


def clean(s) -> str:
    s = "" if s is None else str(s)
    return re.sub(r"\s+", " ", s.replace(" ", " ")).strip()


def first_name(action: str, fallback: str = "this person") -> str:
    tok = clean(action).split(" ")[0] if action else ""
    return tok if tok[:1].isupper() and tok.isalpha() and tok not in ("The", "A", "An", "He", "She", "They", "I") \
        else fallback


def lower_first(s: str) -> str:
    words = s.split()
    if len(words) > 1 and sum(w[:1].isupper() for w in words) > len(words) / 2:  # Title Case action labels
        return " ".join(w if w == "I" or w[1:2].isupper() else w.lower() for w in words)
    return s[:1].lower() + s[1:] if s and not s[:2].isupper() else s


