def review_sample(rows: list[dict], n: int = 3) -> list[dict]:
    """n items per frame x polarity cell, taken from the same scenarios so pos and neg can be read side by side."""
    by_scn = {}
    for r in rows:
        by_scn.setdefault(r["scenario_id"], []).append(r)
    order = sorted(by_scn, key=lambda s: h(s))
    out = []
    for f in sorted({r["frame"] for r in rows}):
        taken = 0
        for s in order:
            cell = {r["item_id"]: r for r in by_scn[s] if r["frame"] == f}
            pos = sorted(i for i, r in cell.items() if r["polarity"] == "pos")
            if not pos:
                continue
            # several sub-contrasts per scenario: rotate through them, and pair each pos with its own neg
            p = pos[taken % len(pos)]
            q = p.replace(f"-{f}-pos", f"-{f}-neg")
            if q not in cell:
                continue
            out += [cell[p], cell[q]]
            taken += 1
            if taken == n:
                break
    return out


def finish(cid: str, items: list, held: list, beh: list, gen: Gen | None = None):
    d = item_dir(cid)
    pending = gen.flush() if gen else 0
    write_jsonl(d / "items.jsonl", items)
    write_jsonl(d / "heldout.jsonl", held)
    write_jsonl(d / "behavior.jsonl", beh)
    write_jsonl(d / "review_sample.jsonl", review_sample(items))
    scn = len({r["scenario_id"] for r in items})
    cells = {}
    for r in items:
        k = f"{r['frame']}-{r['polarity']}"
        cells[k] = cells.get(k, 0) + 1
    print(f"[{cid}] scenarios {scn} items {len(items)} {cells} heldout {len(held)} behavior {len(beh)}"
          + (f" | {pending} requests pending" if pending else ""), flush=True)
