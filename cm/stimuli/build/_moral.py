def ab_choice(question: str, opt1: str, opt2: str, key: str) -> tuple[str, str, str]:
    """Two-option question with positions counterbalanced by key. Returns (text, letter of opt1, letter of opt2)."""
    if int(h(key), 16) % 2 == 0:
        a, b, l1, l2 = opt1, opt2, "A", "B"
    else:
        a, b, l1, l2 = opt2, opt1, "B", "A"
    return (f"{question}\n\nA) {a}\nB) {b}\n\nAnswer with A or B only.", l1, l2)


def len_ratio(a: str, b: str) -> float:
    return len(a) / max(1, len(b))


